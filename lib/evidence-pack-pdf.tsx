import {
  Document,
  Page,
  Text,
  View,
  StyleSheet,
  renderToBuffer,
} from "@react-pdf/renderer";
import { omissionLabel, rangeLabel, type PackContents } from "./evidence-pack";
import { formatDateTime } from "./dates";

/**
 * The evidence pack: one carer, one period, one PDF.
 *
 * Plain on purpose. This is read across a table by an inspector who has
 * twenty minutes, so it is dated, labelled, and says on the first page what it
 * does and does not contain. Nothing is styled to impress.
 */

export interface PackRow {
  /** Left column — usually a date. */
  when: string;
  /** What it was. */
  what: string;
  /** Free-text detail, printed small under the line. */
  detail?: string | null;
  /** Right column — status, outcome, result. */
  status?: string | null;
}

export interface PackSectionData {
  key: string;
  label: string;
  rows: PackRow[];
}

export interface EvidencePackData {
  personName: string;
  personEmail: string | null;
  organisationName: string;
  generatedAt: Date;
  generatedBy: string;
  from: string | null;
  contents: PackContents;
  sections: PackSectionData[];
}

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 10, color: "#111827", fontFamily: "Helvetica" },
  brand: { fontSize: 9, letterSpacing: 2, color: "#0f8178", marginBottom: 6 }, // the site's teal, not indigo
  title: { fontSize: 20, fontFamily: "Helvetica-Bold", marginBottom: 2 },
  subtitle: { fontSize: 11, color: "#374151", marginBottom: 18 },
  metaRow: { flexDirection: "row", marginBottom: 3 },
  metaLabel: { width: 120, color: "#6b7280" },
  metaValue: { flex: 1 },
  sectionHeading: {
    fontSize: 12,
    fontFamily: "Helvetica-Bold",
    marginTop: 18,
    marginBottom: 6,
    paddingBottom: 3,
    borderBottom: "1 solid #d1d5db",
  },
  row: {
    flexDirection: "row",
    paddingVertical: 4,
    borderBottom: "0.5 solid #e5e7eb",
  },
  when: { width: 78, color: "#374151" },
  what: { flex: 1, paddingRight: 8 },
  status: { width: 96, textAlign: "right", color: "#374151" },
  detail: { fontSize: 8, color: "#6b7280", marginTop: 2 },
  note: { fontSize: 9, color: "#6b7280", marginTop: 6 },
  bullet: { fontSize: 9, color: "#374151", marginBottom: 2 },
  footer: {
    position: "absolute",
    bottom: 24,
    left: 40,
    right: 40,
    fontSize: 8,
    color: "#9ca3af",
    flexDirection: "row",
    justifyContent: "space-between",
  },
});

function fmtDateTime(d: Date): string {
  return formatDateTime(d, {
    day: "numeric",
    month: "long",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function EvidencePackDoc({ data }: { data: EvidencePackData }) {
  const footer = (
    <View style={styles.footer} fixed>
      <Text>
        {data.personName} — evidence pack — {data.organisationName}
      </Text>
      <Text
        render={({ pageNumber, totalPages }) => `${pageNumber} of ${totalPages}`}
      />
    </View>
  );

  return (
    <Document
      title={`Evidence pack — ${data.personName}`}
      author={data.organisationName}
    >
      <Page size="A4" style={styles.page}>
        <Text style={styles.brand}>MY CARE ACADEMY</Text>
        <Text style={styles.title}>{data.personName}</Text>
        <Text style={styles.subtitle}>Staff evidence pack</Text>

        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Organisation</Text>
          <Text style={styles.metaValue}>{data.organisationName}</Text>
        </View>
        {data.personEmail && (
          <View style={styles.metaRow}>
            <Text style={styles.metaLabel}>Email</Text>
            <Text style={styles.metaValue}>{data.personEmail}</Text>
          </View>
        )}
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Period covered</Text>
          <Text style={styles.metaValue}>
            {rangeLabel(data.from, data.generatedAt)}
          </Text>
        </View>
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Generated</Text>
          <Text style={styles.metaValue}>{fmtDateTime(data.generatedAt)}</Text>
        </View>
        <View style={styles.metaRow}>
          <Text style={styles.metaLabel}>Generated by</Text>
          <Text style={styles.metaValue}>{data.generatedBy}</Text>
        </View>

        <Text style={styles.sectionHeading}>What this pack contains</Text>
        {data.contents.included.map((s) => (
          <Text key={s.key} style={styles.bullet}>
            • {s.label} — {s.count} {s.count === 1 ? "entry" : "entries"}
          </Text>
        ))}
        {data.contents.included.length === 0 && (
          <Text style={styles.bullet}>• Nothing on file for this period.</Text>
        )}

        {data.contents.omitted.length > 0 && (
          <>
            <Text style={styles.sectionHeading}>Not included</Text>
            {data.contents.omitted.map((s) => (
              <Text key={s.key} style={styles.bullet}>
                • {s.label} — {omissionLabel(s.reason)}
              </Text>
            ))}
            <Text style={styles.note}>
              Sections marked &quot;not included in this organisation&apos;s plan&quot; are
              not held on this system. They may be recorded elsewhere.
            </Text>
          </>
        )}

        {footer}
      </Page>

      {data.sections.map((section) => (
        <Page key={section.key} size="A4" style={styles.page}>
          <Text style={styles.sectionHeading}>{section.label}</Text>
          {section.rows.map((row, i) => (
            <View key={i} style={styles.row} wrap={false}>
              <Text style={styles.when}>{row.when}</Text>
              <View style={styles.what}>
                <Text>{row.what}</Text>
                {row.detail && <Text style={styles.detail}>{row.detail}</Text>}
              </View>
              {row.status && <Text style={styles.status}>{row.status}</Text>}
            </View>
          ))}
          {footer}
        </Page>
      ))}
    </Document>
  );
}

export function renderEvidencePack(data: EvidencePackData): Promise<Buffer> {
  return renderToBuffer(<EvidencePackDoc data={data} />);
}
